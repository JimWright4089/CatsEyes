#include <Arduino.h>
#include "stopWatch.hpp"

//----------------------------------------------------------------------------
//  Global and Static data
//----------------------------------------------------------------------------

//----------------------------------------------------------------------------
//  Purpose:
//   Constructor
//
//  Notes:
//
//----------------------------------------------------------------------------
StopWatch::StopWatch() :
  m_last_time(0),
  m_wait_time(1000)
{
}

//----------------------------------------------------------------------------
//  Purpose:
//   Constructor
//
//  Notes:
//
//----------------------------------------------------------------------------
StopWatch::StopWatch(uint64_t wait_time) :
  m_last_time(0),
  m_wait_time(wait_time)
{
}

//----------------------------------------------------------------------------
//  Purpose:
//   Return the milliseconds
//
//  Notes:
//
//----------------------------------------------------------------------------
uint64_t StopWatch::now(void)
{
  return millis();
}

//----------------------------------------------------------------------------
//  Purpose:
//   Getter Setter
//
//  Notes:
//
//----------------------------------------------------------------------------
void StopWatch::set_time(uint64_t wait_time)
{
  m_wait_time = wait_time;
}

//----------------------------------------------------------------------------
//  Purpose:
//   Is the timer finished
//
//  Notes:
//
//----------------------------------------------------------------------------
bool StopWatch::is_expired(void)
{
  if ((now() - m_last_time) > m_wait_time)
  {
    return true;
  }
  return false;
}

//----------------------------------------------------------------------------
//  Purpose:
//   Reset the time back to start
//
//  Notes:
//
//----------------------------------------------------------------------------
void StopWatch::reset(void)
{
  m_last_time = now();
}

//----------------------------------------------------------------------------
//  Purpose:
//   Return the amount of time left
//
//  Notes:
//
//----------------------------------------------------------------------------
int64_t StopWatch::get_time_left()
{
  return m_wait_time - (now() - m_last_time);
}

